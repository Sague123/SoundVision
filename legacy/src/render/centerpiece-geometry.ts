/** Насколько центр обложки выше центра кадра: под ней ещё строки текста. */
export const CENTERPIECE_LIFT = 0.04;
/** Радиус пустого круга, в который помещаются обложка и две строки текста. */
export const CENTERPIECE_HOLE = 0.195;
